export type Frame = { t: number; knee: number; hip: number };

const FRAME_MS = 33;
const REP_STEPS = 30;

function nextTimestamp(frames: Frame[]): number {
    return frames.length === 0 ? 0 : frames[frames.length - 1].t + FRAME_MS;
}

function hold(frames: Frame[], count: number, knee: number, hip: number): void {
    const start = nextTimestamp(frames);
    for (let i = 0; i < count; i++) {
        frames.push({ t: start + i * FRAME_MS, knee, hip });
    }
}

/**
 * One squat: 1 s descent from `top` to `bottom` and 1 s ascent back, appended right after the last frame.
 */
function squat(frames: Frame[], bottom: number, top: number): void {
    const start = nextTimestamp(frames);
    for (let i = 0; i < REP_STEPS; i++) {
        const value = top - ((top - bottom) * i) / REP_STEPS;
        frames.push({ t: start + i * FRAME_MS, knee: value, hip: value + 2 });
    }
    for (let i = 0; i <= REP_STEPS; i++) {
        const value = bottom + ((top - bottom) * i) / REP_STEPS;
        frames.push({
            t: start + (REP_STEPS + i) * FRAME_MS,
            knee: value,
            hip: value + 2,
        });
    }
}

function build(steps: (frames: Frame[]) => void): Frame[] {
    const frames: Frame[] = [];
    steps(frames);

    return frames;
}

/** Person stands still for 1 s, then performs two squats with a short pause between them. */
export const idealTwoReps: Frame[] = build((frames) => {
    hold(frames, 30, 170, 172);
    squat(frames, 90, 170);
    hold(frames, 15, 170, 172);
    squat(frames, 90, 170);
    hold(frames, 15, 170, 172);
});

/** Recording starts while the person is still straightening up from a squat, then two squats follow. */
export const startsMidDescent: Frame[] = build((frames) => {
    for (let i = 0; i < 15; i++) {
        frames.push({ t: i * FRAME_MS, knee: 140 + i, hip: 145 + i });
    }
    hold(frames, 30, 170, 172);
    squat(frames, 90, 170);
    hold(frames, 15, 170, 172);
    squat(frames, 90, 170);
    hold(frames, 15, 170, 172);
});

